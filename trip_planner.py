import streamlit as st

st.set_page_config(page_title="Trip Planner", page_icon="✈️", layout="centered")

st.title("✈️ Trip Planner - תכנון הטיול הבא שלך!")

st.markdown("בחר את ההעדפות שלך ותקבל המלצה מדויקת על מדינה שמתאימה לך 🌍")

st.markdown("---")

# שאלות
continent = st.radio("לאיזה יבשת היית רוצה לטוס?", ["אירופה", "אסיה", "אמריקה", "אפריקה"])
vibe = st.radio("איזו אווירה אתה אוהב?", ["עיר גדולה", "כפר פסטורלי", "אי רגוע", "הרים ושלג"])
food = st.radio("מה הכי מדבר אליך?", ["מסעדות יוקרה", "Street Food", "מטבח מקומי", "לא אכפת לי"])
activities = st.radio("מה אתה מעדיף לעשות?", ["טיולים בטבע", "שופינג", "ים ובריכה", "אתרים היסטוריים"])
budget = st.radio("מה התקציב שלך?", ["זול", "בינוני", "יוקרתי"])
weather = st.radio("איזה מזג אוויר אתה אוהב?", ["חם 🌞", "קר ❄️", "מתון 🌤️"])
language = st.radio("איזו שפה תרגיש בה בנוח?", ["אנגלית", "צרפתית", "ספרדית", "לא משנה לי"])
transport = st.radio("איך אתה אוהב להתנייד?", ["רכב שכור", "תחבורה ציבורית", "הליכה ברגל"])
trip_length = st.radio("כמה זמן הטיול?", ["סופ\"ש", "שבוע", "שבועיים", "יותר מחודש"])
companion = st.radio("עם מי אתה נוסע?", ["לבד", "בן/בת זוג", "חברים", "משפחה"])

st.markdown("---")

if st.button("📍 קבל המלצה על יעד"):
    if continent == "אירופה" and vibe == "עיר גדולה" and food == "שופינג":
        st.success("יעד מומלץ: פריז, צרפת 🇫🇷")
    elif continent == "אסיה" and vibe == "אי רגוע":
        st.success("יעד מומלץ: פוקט, תאילנד 🇹🇭")
    elif continent == "אמריקה" and vibe == "הרים ושלג":
        st.success("יעד מומלץ: קולורדו, ארה\"ב 🇺🇸")
    elif continent == "אפריקה" and food == "מטבח מקומי":
        st.success("יעד מומלץ: מרקש, מרוקו 🇲🇦")
    else:
        st.success("יעד מומלץ: ליסבון, פורטוגל 🇵🇹")

st.markdown("---")
st.info("🧭 רוצה עזרה בשימוש? לחץ על מדריך למשתמש בתפריט הצד!")

